const assert=require('node:assert/strict')
const ts=require('typescript'),fs=require('node:fs')
const m={exports:{}}
new Function('module','exports',ts.transpileModule(fs.readFileSync('lib/vendaInstalacaoProducao.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText)(m,m.exports)
const {refItemProducaoInstalacao,disponibilidadePeca,validarRegistroInstalacao}=m.exports
assert.equal(refItemProducaoInstalacao({id:'UUID'},0),'UUID')
assert.equal(refItemProducaoInstalacao({item_ref:'outra-ref'},0),'item-1')
assert.equal(refItemProducaoInstalacao({},1),'item-2')
const ref='item-1'
const ordem=(status,quantidade=2,bloqueada=false,item_ref=ref,tipo_producao='esquadria')=>({status,quantidade,bloqueada,item_ref,tipo_producao})
const sem=disponibilidadePeca([],ref,3)
assert.equal(sem.estado,'sem_ordem');assert.equal(sem.prontas,0)
const em=disponibilidadePeca([ordem('em_producao')],ref,3)
assert.equal(em.estado,'aguardando');assert.equal(em.prontas,0)
const parcial=disponibilidadePeca([ordem('concluida',2),ordem('aguardando',1)],ref,3)
assert.equal(parcial.estado,'parcial');assert.equal(parcial.prontas,2)
const completa=disponibilidadePeca([ordem('concluida',3),ordem('concluida',3,false,'outro'),ordem('concluida',3,false,ref,'contramarco')],ref,3)
assert.equal(completa.estado,'pronta');assert.equal(completa.prontas,3)
assert.equal(disponibilidadePeca([ordem('concluida',3,true)],ref,3).prontas,0)
const validar=(novo,status,disponibilidade=parcial,existente=0)=>validarRegistroInstalacao({existente,novo,status,quantidadePlanejada:3,disponibilidade})
assert.equal(validar(2,'em_instalacao'),null)
assert.match(validar(3,'instalado'),/Produção insuficiente/)
assert.equal(validar(3,'instalado',completa),null)
assert.match(validar(2,'instalado'),/quantidade total/)
assert.equal(validar(0,'em_instalacao'),null) // obra iniciada, mas primeira peça ainda não instalada
assert.match(validar(0,'em_instalacao',sem),/produzidas disponíveis/)
assert.match(validar(2,'pendente'),/não pode possuir/)
assert.match(validar(4,'instalado'),/inválida/)
assert.match(validar(1.5,'em_instalacao'),/inválida/)
assert.match(validar(1,'em_instalacao',sem),/Produção insuficiente/)
assert.equal(validar(0,'pendencia',sem),null)
assert.equal(validar(0,'pendente',sem),null)
assert.equal(validar(1,'em_instalacao',sem,1),'Produção insuficiente: apenas 0 de 3 peça(s) concluída(s) e liberada(s).')
console.log('PASS: referência por peça, quantidades produzidas, instalação parcial e bloqueios.')
