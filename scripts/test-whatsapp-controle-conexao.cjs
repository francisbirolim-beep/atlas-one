const fs=require('node:fs')
const assert=require('node:assert/strict')
const canais=fs.readFileSync('app/api/integracoes/whatsapp/canais/route.ts','utf8')
const permissoes=fs.readFileSync('app/api/integracoes/whatsapp/canais/permissoes/route.ts','utf8')
const tela=fs.readFileSync('app/whatsapp/numeros/page.tsx','utf8')
const configuracao=fs.readFileSync('app/whatsapp/configuracao/page.tsx','utf8')
const gateway=fs.readFileSync('scripts/whatsapp-gateway.mjs','utf8')
const edge=fs.readFileSync('supabase/functions/whatsapp-gateway/index.ts','utf8')
assert.match(canais,/podeOperarConexao\(usuario, canal\.id\)/)
assert.match(canais,/pode_gerenciar_conexao === true/)
assert.match(canais,/conexao_pausada: acao === 'desconectar'/)
assert.doesNotMatch(canais,/session_slug:\s*crypto\.randomUUID\(\)/,'Reconexão não pode descartar credenciais.')
assert.match(canais,/gateway_qr_data_url: podeConectar \? canal\.gateway_qr_data_url : null/)
assert.match(permissoes,/usuario\.role !== 'master'/)
assert.match(permissoes,/pode_gerenciar_conexao: podeGerenciarConexao/)
assert.match(tela,/Conectar \/ recuperar QR/)
assert.match(tela,/> Desconectar/)
assert.match(tela,/podeGerenciarConexao:proxima\.pode_gerenciar_conexao/)
assert.match(configuracao,/podeGerenciarConexao:proxima\.pode_gerenciar_conexao/)
assert.match(gateway,/allChannels\.filter\(c => !pausedChannels\.has\(c\.id\)\)/)
assert.match(gateway,/syncFullHistory: true/)
assert.match(gateway,/shouldSyncHistoryMessage: \(\) => true/)
assert.match(gateway,/fs\.renameSync\(sessionDir/)
assert.doesNotMatch(gateway,/fs\.rmSync\(sessionDir/)
assert.match(edge,/channel\.conexao_pausada === true/)
assert.match(edge,/accepted: false, paused: true/)
console.log('PASS: conexão, QR, histórico, pausa e permissões protegidos.')
