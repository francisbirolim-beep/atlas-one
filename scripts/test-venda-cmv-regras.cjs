const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const ts = require('typescript')
const modulo = { exports: {} }
const codigo = fs.readFileSync('lib/vendaCmvRegras.ts', 'utf8')
vm.runInNewContext(ts.transpileModule(codigo, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: modulo.exports, module: modulo })
const custo = modulo.exports.custoRealCompraConfirmada
assert.equal(custo('cotacao', 1500), 0, 'Cotação ainda não virou compra')
assert.equal(custo('necessidade', 1500), 0)
assert.equal(custo('aprovado', null), 0, 'Compra sem preço real não gera CMV fictício')
assert.equal(custo('aprovado', 1250.499), 1250.5)
assert.equal(custo('pedido_emitido', 200), 200)
assert.equal(custo('aguardando_entrega', 135), 135)
assert.equal(custo('recebido', 399), 399)
assert.equal(custo('comprado', 99.90), 99.9)
assert.equal(custo('cancelado', 99), 0)
assert.equal(custo('recebido', -10), 0)
assert.equal(custo('recebido', Number.NaN), 0)
console.log('PASS: cotação não vira CMV, estados de compra e valores realizados válidos.')
