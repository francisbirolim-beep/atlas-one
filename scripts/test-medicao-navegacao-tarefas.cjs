const fs = require('node:fs')
const assert = require('node:assert/strict')

const ler = path => fs.readFileSync(path, 'utf8')
const shell = ler('components/system/AppShell.tsx')
const voltar = ler('components/system/AtlasVoltar.tsx')
const venda = ler('components/clientes/VendaObraCentral.tsx')
const painel = ler('components/clientes/VendaMedidaFinal.tsx')
const status = ler('components/clientes/VendaMedidaStatus.tsx')
const campo = ler('components/system/MedicaoFinalFieldSummary.tsx')
const api = ler('app/api/medicao-final/[id]/atribuir-conferencia/route.ts')

assert.match(shell, /<AtlasVoltar\s*\/>/, 'Botão de voltar deve existir em todas as telas internas')
assert.match(voltar, /Voltar à tela anterior/)
assert.match(voltar, /atlas-medicao-retorno:/)
assert.match(painel, /atlas-medicao-retorno:/)
assert.match(venda, /\?aba=medida-final|searchParams\.get|window\.location\.search/)
assert.match(venda, /<VendaMedidaStatus/)
assert.match(status, /Não iniciada/)
assert.match(status, /Concluída/)
assert.match(campo, /atribuir-conferencia/)
assert.match(campo, /GABRIELLE|DAIANE/)
assert.match(api, /solicitante\.role !== 'master'/)
assert.match(api, /idDaTarefa\(medicao\.id, usuario\.id\)/)
assert.match(api, /\.eq\('empresa_id', solicitante\.empresa_id\)/)
assert.match(api, /status_operacional/)
assert.match(api, /medicao_final_conferencia/)
console.log('PASS: voltar global, retorno à venda, status de medição, tarefas múltiplas por responsável e antidualidade.')
