// Verifica que Kanban não apaga/forja data física de recebimento.
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const ts=require('typescript')
const source=fs.readFileSync(path.resolve(__dirname,'../lib/comprasStatusGuard.ts'),'utf8')
const output=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText
const mod={exports:{}}
new Function('module','exports',output)(mod,mod.exports)
const guard=mod.exports.impedirRetornoDeRecebimento
assert.equal(guard([{id:'a',status:'cotacao',recebido_em:null}],'comprado'),null)
assert.equal(guard([{id:'a',status:'recebido',recebido_em:null}],'cotacao'),null)
assert.match(guard([{id:'a',status:'recebido',recebido_em:'2026-10-10T12:00:00Z'}],'cotacao'),/estorno específico/)
assert.match(guard([{id:'a',status:'recebido',recebido_em:'2026-10-10T12:00:00Z'},{id:'b',status:'cotacao',recebido_em:null}],'comprado'),/estorno específico/)
assert.equal(guard([{id:'a',status:'recebido',recebido_em:'2026-10-10T12:00:00Z'}],'recebido'),null)
assert.match(guard([{id:'a',status:'cancelado',recebido_em:null}],'comprado'),/cancelados/)
const route=fs.readFileSync(path.resolve(__dirname,'../app/api/vendas/materiais/status-lote/route.ts'),'utf8')
assert.doesNotMatch(route,/atualizacao\.recebido_em\s*=/,'Não escrever nem apagar o carimbo de recebimento')
assert.match(route,/necessidadesValidadas = data \|\| \[\]/,'Validar as necessidades antes de editar materiais')
assert.match(route,/impedirRetornoDeRecebimento\(necessidadesValidadas, status\)/,'Garantir bloqueio no servidor')
assert.match(route,/idsValidos\.length !== materialIds\.length/,'Não aceitar IDs técnicos de outras obras')
assert.match(route,/\(data \|\| \[\]\)\.length !== necessidadeIds\.length/,'Não aceitar IDs de compras de outra obra')
const ui=fs.readFileSync(path.resolve(__dirname,'../components/clientes/VendaObraCentral.tsx'),'utf8')
assert.match(ui,/async function moverCompraPorId\(/,'Permitir mover compras com o mesmo fluxo no desktop e no celular')
assert.match(ui,/aria-label=\{`Mover material/,'Cada card tem seleção de etapa acessível por toque')
assert.match(ui,/setComprasColunasExpandidas/,'Preservar botão para expandir cards')
assert.match(ui,/VendaCotacaoItensModal/,'Preservar seleção parcial nas cotações')
assert.match(ui,/json\.aviso/,'Exibir aviso administrativo para o usuário')
console.log('PASS: Compras — recebimento protegido, IDs validados, toque móvel e cotação parcial preservada.')
