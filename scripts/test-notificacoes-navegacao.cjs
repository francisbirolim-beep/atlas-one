const assert=require('node:assert/strict')
const fs=require('node:fs')
const ler=f=>fs.readFileSync(f,'utf8')
const url='/configuracoes/notificacoes'
const nav=ler('components/configuracoes/ConfiguracoesNav.tsx')
const settings=ler('app/configuracoes/page.tsx')
const perfil=ler('components/system/AppTopbar.tsx')
const mobile=ler('components/system/MobileFavorites.tsx')
const pagina=ler('app/configuracoes/notificacoes/page.tsx')
for(const [nome,valor] of Object.entries({nav,settings,perfil,mobile})){
 assert(valor.includes(url),nome+' deve apontar a rota')
 assert(valor.includes('Notificações e Lembretes'),nome+' deve conter nome claro')
}
const inicioMenu=perfil.indexOf('{perfilAberto && (')
const fimMenu=perfil.indexOf('{buscaAberta && (')
const trechoPerfil=perfil.slice(inicioMenu,fimMenu)
assert(inicioMenu>0&&fimMenu>inicioMenu)
assert(trechoPerfil.includes('<Link href="/configuracoes/notificacoes"'),'usuários não master precisam ver o link')
assert(trechoPerfil.indexOf('<Link href="/configuracoes/notificacoes"')>trechoPerfil.indexOf("usuario?.role === 'master' && <Link"),'link deve ficar fora da condição master')
assert(mobile.indexOf('Minhas preferências')<mobile.indexOf('{isMaster && ('),'atalho mobile pessoal deve aparecer para todos')
assert(nav.includes("href: '/configuracoes/notificacoes'"))
assert(settings.includes('<Link href="/configuracoes/notificacoes"'))
assert(pagina.includes('Central de Notificações'))
assert(pagina.includes('href="/" title="Voltar à Visão Geral"'))
console.log('PASS: Configurações, perfil, busca e celular exibem link permanente; funcionário pode navegar.')
