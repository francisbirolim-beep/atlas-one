// Regressao estatica complementar: manter edicao e impedir que exclusao duplique CMV.
const fs=require('node:fs'),assert=require('node:assert/strict')
const api=fs.readFileSync('app/api/vendas/cmv/route.ts','utf8')
const ui=fs.readFileSync('components/clientes/VendaCmvPainel.tsx','utf8')
const report=fs.readFileSync('app/api/relatorios/obras-cmv/route.ts','utf8')
const sql=fs.readFileSync('supabase/migrations/20261013183000_venda_cmv_cancelamento_auditado_v1.sql','utf8')
const cancelar=api.slice(api.indexOf('export async function DELETE('))
assert.match(api,/export async function PATCH\(/)
assert.match(api,/if\(antigo\.cancelado_em\)return erro\('Lançamento cancelado não pode ser editado/)
assert.match(api,/const ativos=\(lancamentos\|\|\[\]\)\.filter\(l=>!l\.cancelado_em\)/)
assert.match(api,/lancamentosCancelados/)
assert.match(cancelar,/const usuario=await autenticarTenant\(req\)/)
assert.match(cancelar,/vendaVerificada\(usuario\.empresa_id,vendaId\)/)
assert.match(cancelar,/eq\('empresa_id',usuario\.empresa_id\)/)
assert.match(cancelar,/eq\('orcamento_id',venda\.orcamento_id\)/)
assert.match(cancelar,/usuario\.role!=='master'&&antigo\.criado_por_id!==usuario\.id/)
assert.match(cancelar,/antigo\.versao!==versao/)
assert.match(cancelar,/\.is\('cancelado_em',null\)/)
assert.match(cancelar,/cancelado_em:agora/)
assert.match(cancelar,/motivo_cancelamento:motivo/)
assert.match(cancelar,/atualizado_por_id:usuario\.id/)
assert.match(cancelar,/versao:versao\+1/)
assert.doesNotMatch(cancelar,/\.insert\(|\.delete\(/)
assert.match(ui,/Editar lançamento/)
assert.match(ui,/Confirmar exclusão/)
assert.match(ui,/motivoExclusao\.trim\(\)\.length<8/)
assert.match(ui,/Histórico de correções/)
assert.match(ui,/lancamentosCancelados/)
assert.match(ui,/method:'DELETE'/)
assert.match(report,/lancamentos\.filter\(l => !l\.cancelado_em\)/)
assert.match(sql,/ADD COLUMN IF NOT EXISTS cancelado_em timestamptz/)
assert.match(sql,/WHERE cancelado_em IS NULL/)
console.log('PASS: cancelamento logico de CMV, autorizacao, concorrencia, auditoria, exclusao do relatorio e UI.')
