const assert = require('node:assert/strict')
const fs = require('node:fs')
const Module = require('node:module')
const ts = require('typescript')
const fullname = 'lib/vendaCmvLancamentos.ts'
const src = fs.readFileSync(fullname,'utf8')
const js = ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText
const m = new Module(fullname,module); m.filename=fullname;m.paths=Module._nodeModulePaths(process.cwd());m._compile(js,fullname)
const {separarLancamentosCmv}=m.exports
const antes=[{id:'primeiro',valor:240.25,cancelado_em:null},{id:'duplicado',valor:240.25,cancelado_em:'2026-10-13T22:00:00Z'}]
const original=JSON.stringify(antes)
const {ativos,excluidos}=separarLancamentosCmv(antes)
assert.deepEqual(ativos.map(l=>l.id),['primeiro'])
assert.deepEqual(excluidos.map(l=>l.id),['duplicado'])
assert.equal(ativos.reduce((s,l)=>s+l.valor,0),240.25,'CMV não duplica após exclusão')
assert.equal(JSON.stringify(antes),original,'Separação não altera origem ou comprovantes')
assert.equal(separarLancamentosCmv([]).ativos.length,0)
const api=fs.readFileSync('app/api/vendas/cmv/route.ts','utf8')
const del=api.slice(api.indexOf('export async function DELETE'))
const patch=api.slice(api.indexOf('export async function PATCH'),api.indexOf('export async function DELETE'))
const rel=fs.readFileSync('app/api/relatorios/obras-cmv/route.ts','utf8')
const ui=fs.readFileSync('components/clientes/VendaCmvPainel.tsx','utf8')
const migration=fs.readFileSync('supabase/migrations/20261013210907_cmv_cancelamento_auditado_aplicado.sql','utf8')
assert.match(api,/const \{ativos,excluidos\}=separarLancamentosCmv\(linhas\)/)
assert.match(api,/lancamentos:ativos,excluidos/)
assert.match(rel,/separarLancamentosCmv\(lancamentosAtuais\)/)
assert.match(del,/autenticarTenant\(req\)/)
assert.match(del,/vendaVerificada\(usuario\.empresa_id,vendaId\)/)
assert.match(del,/\.eq\('empresa_id',usuario\.empresa_id\)/)
assert.match(del,/\.eq\('venda_obra_id',vendaId\)\.eq\('orcamento_id',venda\.orcamento_id\)/)
assert.match(del,/usuario\.role!=='master'&&antigo\.criado_por_id!==usuario\.id/)
assert.match(del,/antigo\.versao!==versao/)
assert.match(del,/if\(antigo\.cancelado_em\)/)
assert.match(del,/\.eq\('versao',versao\)\.is\('cancelado_em',null\)/)
assert.match(del,/cancelado_em:agora,cancelado_por_id:usuario\.id,cancelado_por_nome:usuario\.nome/)
assert.match(del,/motivo_cancelamento:motivo/)
assert.match(del,/atualizado_por_id:usuario\.id/)
assert.match(del,/versao:versao\+1/)
assert.match(del,/motivo\.length<5/)
assert.doesNotMatch(del,/\.delete\(|storage\.from|\.remove\(|\.insert\(/)
const restore=api.slice(api.indexOf('export async function PUT'))
assert.match(restore,/autenticarTenant\(req\)/)
assert.match(restore,/usuario\.role!=='master'&&antigo\.criado_por_id!==usuario\.id/)
assert.match(restore,/antigo\.versao!==versao/)
assert.match(restore,/cancelado_em:null/)
assert.match(restore,/\.not\('cancelado_em','is',null\)/)
assert.match(restore,/versao:versao\+1/)
assert.doesNotMatch(restore,/\.insert\(|\.delete\(/)
assert.match(patch,/\.is\('cancelado_em',null\)/)
assert.match(ui,/:'Excluir'/)
assert.match(ui,/Confirmar exclusão deste lançamento/)
assert.match(ui,/motivoExclusao\.trim\(\)\.length<5/)
assert.match(ui,/method:'DELETE'/)
assert.match(ui,/Lançamentos excluídos/)
assert.match(ui,/Restaurar lançamento/)
assert.match(ui,/method:'PUT'/)
assert.match(ui,/l\.anexo_url/)
assert.match(migration,/ADD COLUMN IF NOT EXISTS cancelado_em/)
assert.match(migration,/ADD COLUMN IF NOT EXISTS motivo_cancelamento/)
assert.doesNotMatch(migration,/DROP TABLE|DELETE FROM|TRUNCATE/)
console.log('PASS: exclusão lógica do CMV, apenas o item selecionado, motivo, versionamento, tenant, auditoria e totais gerenciais.')
