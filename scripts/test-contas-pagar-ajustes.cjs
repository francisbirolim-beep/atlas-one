const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const fonte = fs.readFileSync(path.join(__dirname,'../lib/contasPagarAjustes.ts'),'utf8')
const js = ts.transpileModule(fonte,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText
const out = {}
new Function('exports',js)(out)
const {calcularBaixaPagar,centavosContaPagar,saldoContaPagar}=out
function confere(campos,expected){
 const r=calcularBaixaPagar({valorTitulo:100,formaPagamento:'pix',...campos})
 assert.equal(r.ok,true,r.erro)
 assert.equal(r.totalDevido,expected)
 assert.equal(r.valorLiquido,expected)
}
confere({valorEntregue:100},100)
confere({valorEntregue:85,valorDesconto:15},85)
confere({valorEntregue:117.55,valorDesconto:5,valorJuros:12.50,valorMulta:10.05},117.55)
const troco=calcularBaixaPagar({valorTitulo:100,formaPagamento:'dinheiro',valorEntregue:120,valorTroco:20})
assert.equal(troco.ok,true)
assert.equal(troco.valorLiquido,100)
assert.equal(troco.valorTroco,20)
assert.equal(calcularBaixaPagar({valorTitulo:100,formaPagamento:'pix',valorEntregue:120,valorTroco:20}).ok,false)
assert.equal(calcularBaixaPagar({valorTitulo:100,formaPagamento:'pix',valorEntregue:80}).ok,false)
assert.equal(calcularBaixaPagar({valorTitulo:100,formaPagamento:'pix',valorEntregue:120}).ok,false)
assert.equal(calcularBaixaPagar({valorTitulo:100,formaPagamento:'pix',valorEntregue:0,valorDesconto:101}).ok,false)
assert.equal(calcularBaixaPagar({valorTitulo:100,formaPagamento:'dinheiro',valorEntregue:99,valorTroco:100}).ok,false)
assert.equal(centavosContaPagar('100.001'),null)
assert.equal(centavosContaPagar('abc'),null)
assert.equal(centavosContaPagar('-10'),null)
assert.equal(centavosContaPagar('0.29'),29)
assert.equal(saldoContaPagar({valor:100,valor_desconto:10,valor_juros:5,valor_multa:2,valor_pago:97,status:'pago'}),0)
assert.equal(saldoContaPagar({valor:100,valor_desconto:10,valor_juros:5,valor_multa:2,valor_pago:0,status:'aberto'}),97)
assert.equal(saldoContaPagar({valor:100,valor_pago:100,status:'pago'}),0)
console.log('PASS: Contas a Pagar — desconto, juros, multa, troco, arredondamento, saldo e validações de baixa.')
