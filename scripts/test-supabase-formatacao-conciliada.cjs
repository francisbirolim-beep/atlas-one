const fs=require('node:fs')
const path=require('node:path')
const crypto=require('node:crypto')
const assert=require('node:assert/strict')
const md5=v=>crypto.createHash('md5').update(v).digest('hex')
const sha256=v=>crypto.createHash('sha256').update(v).digest('hex')
const report=JSON.parse(fs.readFileSync('docs/supabase-formatacao-e-migracoes-nao-aplicadas-manifest.json','utf8'))
const active=fs.readdirSync('supabase/migrations').filter(x=>x.endsWith('.sql'))
const versionSet=new Set(active.map(x=>x.slice(0,14)))
assert.equal(active.length,versionSet.size,'Datas duplicadas no histórico ativo')
assert.ok(active.length>=report.active_versions_after,'Migração desapareceu do histórico ativo')
assert.equal(report.reconciled_entries.length,128,'Esperados 128 SQLs conciliados')
assert.equal(report.reconciled_entries.filter(x=>x.classification==='whitespace_normalized_match').length,126)
assert.equal(report.reconciled_entries.filter(x=>x.classification==='content_difference_including_comments').length,2)
const seenVersions=new Set()
const seenFiles=new Set()
for(const x of report.reconciled_entries){
 assert.ok(!seenVersions.has(x.version),'Repetido: '+x.version)
 seenVersions.add(x.version)
 assert.equal(x.active_file,'supabase/migrations/'+x.version+'_'+x.name+'.sql')
 assert.equal(x.preserved_file,'supabase/migrations-review/20261010-formatacao-e-simultaneas/'+x.version+'_'+x.name+'.sql')
 assert.ok(active.includes(path.basename(x.active_file)),'SQL aplicado ausente: '+x.version)
 const saved=fs.readFileSync(x.active_file),original=fs.readFileSync(x.preserved_file)
 assert.equal(md5(saved),x.active_md5,'SQL aplicado alterado: '+x.version)
 assert.equal(md5(original),x.preserved_md5,'Backup local alterado: '+x.version)
 assert.equal(sha256(original),x.preserved_sha256,'SHA de original inconsistente: '+x.version)
 assert.equal(saved.length,x.active_length)
 assert.equal(original.length,x.preserved_length)
 assert.notEqual(md5(saved),md5(original))
 seenFiles.add(path.basename(x.preserved_file))
}
const preserved=fs.readdirSync('supabase/migrations-review/20261010-formatacao-e-simultaneas').filter(x=>x.endsWith('.sql'))
assert.equal(preserved.length,128,'Backup original ausente ou extra')
for(const file of preserved)assert.ok(seenFiles.has(file),'Arquivo órfão '+file)
assert.equal(report.unapplied_review.length,44,'A auditoria precisa incluir os 44 arquivos')
const currentUnapplied=fs.readdirSync('supabase/migrations-review/20261010').filter(x=>x.endsWith('.sql'))
assert.equal(currentUnapplied.length,44)
const seenUnapplied=new Set()
for(const x of report.unapplied_review){
 assert.ok(!seenUnapplied.has(x.file))
 seenUnapplied.add(x.file)
 assert.ok(currentUnapplied.includes(path.basename(x.file)))
 assert.equal(sha256(fs.readFileSync(x.file)),x.sha256,'Versão não aplicada alterada: '+x.file)
 assert.ok(!active.includes(path.basename(x.file)),'Versão não aplicada na pasta de execução: '+x.file)
}
const counts=Object.fromEntries([...new Set(report.unapplied_review.map(x=>x.status))].map(s=>[s,report.unapplied_review.filter(x=>x.status===s).length]))
assert.deepEqual(counts,report.unapplied_classification_counts)
console.log('PASS: 128 SQLs aplicados e 128 originais com MD5/SHA-256, 44 não aplicadas preservadas e classificadas.')
