const assert = require('node:assert/strict')
const fs = require('node:fs')

async function run() {
  const { ehWVetroVendidoValidado } = await import('../lib/medicaoVendaElegivel.ts')
  assert.equal(ehWVetroVendidoValidado(null), false)
  assert.equal(ehWVetroVendidoValidado({wvetro_fluxo:{origem:'W.Vetro',situacao:'V',validacao_manual_cliente:true}}), false,
    'Origem precisa estar no formato W.Vetro usado no fluxo, não uma origem inventada')
  assert.equal(ehWVetroVendidoValidado({wvetro_fluxo:{origem:'wvetro',situacao:'V',validacao_manual_cliente:true}}), true)
  assert.equal(ehWVetroVendidoValidado({wvetro_fluxo:{origem:'wvetro',situacao:'F',fonte_registro:'historico_validado'}}), true)
  assert.equal(ehWVetroVendidoValidado({wvetro_fluxo:{origem:'wvetro',situacao:'O',fonte_registro:'historico_validado'}}), false)
  assert.equal(ehWVetroVendidoValidado({wvetro_fluxo:{origem:'wvetro',situacao:'V'}}), false)
  assert.equal(ehWVetroVendidoValidado({wvetro_fluxo:{origem:'outro',situacao:'V',validacao_manual_cliente:true}}), false)

  const src = fs.readFileSync('lib/medicaoFinal.ts', 'utf8')
  const inicio = src.indexOf('export async function listarMedicoes')
  const fim = src.indexOf('// Orçamentos que estão', inicio)
  const trecho = src.slice(inicio, fim)
  assert.match(trecho, /\.from\('vendas_obras'\)/)
  assert.match(trecho, /\.eq\('status', 'ativa'\)/)
  assert.match(trecho, /ehWVetroVendidoValidado/)
  assert.match(trecho, /\.filter\(m => m\.orcamento_id && vendidos\.has\(m\.orcamento_id\)\)/)
  assert.match(src, /return vendidos\.has\(o\.id\) && !jaTem\.has\(o\.id\)/)
  const cliente = fs.readFileSync('app/producao/medicao-final/cliente/[clienteId]/page.tsx','utf8')
  assert.match(cliente, /\.from\('vendas_obras'\)\.select\('orcamento_id'\)\.eq\('status', 'ativa'\)/)

  const parcial = fs.readFileSync('lib/medicaoParcialNotificacoesServer.ts','utf8')
  const total = fs.readFileSync('lib/medicaoFinalAutomacaoServer.ts','utf8')
  assert.match(parcial, /atlas:medicao:revisao-parcial:/)
  assert.match(total, /atlas:medicao:revisao:/)
  assert.match(parcial, /\.from\('tarefas'\)\.insert\(/)
  assert.match(parcial, /\.from\('notificacoes'\)\.insert\(/)
  const endpoint = fs.readFileSync('app/api/medicao-final/[id]/conferencia/route.ts','utf8')
  assert.match(endpoint, /ehWVetroVendidoValidado\(orcamento\)/)
  assert.match(endpoint, /\.eq\('status', 'ativa'\)/)
  console.log('PASS: Medida Final mostra somente vendas ativas/W.Vetro validado; canceladas e propostas ficam fora.')
  console.log('PASS: envio parcial e total geram cartões distintos para o responsável sem duplicar por reenvio.')
}
run().catch(err => {console.error(err);process.exitCode=1})
