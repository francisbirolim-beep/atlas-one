const assert=require('node:assert/strict')
const fs=require('node:fs'),ts=require('typescript'),Module=require('node:module')
const file='lib/vendaCmvEtapas.ts'
const out=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText
const mod=new Module(file,module);mod.filename=file;mod.paths=Module._nodeModulePaths(process.cwd());mod._compile(out,file)
const separar=mod.exports.separarEtapasCmv
const compra={id:'1',valor:832,categoria:'perfil',quantidade:100,unidade:'KG'}
const antiga=separar([compra])
assert.equal(antiga.totalComprado,832,'lançamento histórico sem etapa deve permanecer comprado')
assert.equal(antiga.totalRecebido,0)
const movida=separar([{...compra,etapa_cmv:'recebido'}])
assert.equal(movida.totalComprado,0)
assert.equal(movida.totalRecebido,832)
assert.equal(movida.comprados.length+movida.recebidos.length,1,'reclassificação não duplica')
assert.equal(movida.recebidos[0].id,compra.id,'preserva mesmo ID')
const duas=separar([{...compra,etapa_cmv:'comprado'},{...compra,id:'2',valor:915.2,etapa_cmv:'recebido'}])
assert.equal(duas.totalComprado,832)
assert.equal(duas.totalRecebido,915.2)
const soma=duas.totalComprado+duas.totalRecebido
assert.equal(Math.round(soma*100),174720)
const api=fs.readFileSync('app/api/vendas/cmv/route.ts','utf8')
const ui=fs.readFileSync('components/clientes/VendaCmvPainel.tsx','utf8')
const sql=fs.readFileSync('supabase/migrations/20261014020500_venda_cmv_destino_etapa_v1.sql','utf8')
assert.match(api,/etapasDisponiveis/)
assert.ok(api.includes("if(etapa_cmv==='recebido'&&origem!=='compra')"))
assert.ok(api.includes("if(etapa_cmv==='recebido'&&!txt(form.get('documento'),100))"))
assert.ok(api.includes("etapa_cmv==='recebido'?{etapa_cmv}:{}"))
assert.match(api,/antigo.etapa_cmv==='recebido'/)
assert.match(ui,/Destino do lançamento \*/)
assert.match(ui,/Custo comprado — pedido \/ cotação/)
assert.match(ui,/Custo recebido — nota fiscal \/ romaneio/)
assert.match(ui,/etapaEdicao/)
assert.match(ui,/etapa_cmv==='recebido'/)
assert.match(ui,/etapasDisponiveis/)
assert.match(ui,/separarEtapasCmv/)
assert.match(ui,/onMudanca\?\.\(\(json\.lancamentos as Lancamento\[\]\)\.filter\(l=>l\.etapa_cmv!=='recebido'\)/)
assert.match(sql,/ADD COLUMN IF NOT EXISTS etapa_cmv text NOT NULL DEFAULT 'comprado'/)
assert.match(sql,/CHECK\(etapa_cmv IN \('comprado','recebido'\)\)/)
assert.doesNotMatch(sql,/DROP TABLE|TRUNCATE|DELETE FROM/)
console.log('PASS: destino explícito, histórico sem alterações, reclassificação mesmo ID, valor por etapa, sem duplicação, migração aditiva.')
