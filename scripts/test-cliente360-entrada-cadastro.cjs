const assert = require('node:assert/strict')
const fs = require('node:fs')
const page = fs.readFileSync('app/clientes/[id]/page.tsx', 'utf8')
const central = fs.readFileSync('app/clientes/[id]/central/page.tsx', 'utf8')
const dashboard = fs.readFileSync('components/clientes/Cliente360DashboardV2.tsx', 'utf8')
const listado = fs.readFileSync('app/clientes/page.tsx','utf8')
assert.match(listado, /\/clientes\/\$\{c\.id\}\/central/)
assert.match(central, /!searchParams\?\.has\('aba'\).*redirect\('\/clientes\/' \+ encodeURIComponent\(id\)\)/)
assert.match(page, /<Cliente360DashboardV2 clienteId=\{id\}/)
assert.match(dashboard, /useState<Aba>\('cadastro'\)/)
assert.match(dashboard, /label:'Cadastro'/)
assert.match(dashboard, /<CadastroCliente360 cliente=\{cliente\} obras=\{obras\}/)
assert.match(central, /aba === 'andamento' \? <Cliente360Andamento clienteId=\{id\} \/> : <Cliente360Dashboard clienteId=\{id\} \/>/)
assert.match(central, /central\?aba=central/)
assert.match(page, /central\?aba=central/)
assert.match(central, /central\?aba=andamento/)
console.log('PASS: entrada antiga abre cadastro aprovado; Central anterior e Andamento preservados.')
