const assert=require('node:assert/strict')
const fs=require('node:fs')
const vm=require('node:vm')
const ts=require('typescript')
const importar=(arquivo,mocks={})=>{
 const m={exports:{}}
 vm.runInNewContext(ts.transpileModule(fs.readFileSync(arquivo,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,
  {exports:m.exports,module:m,require:n=>{if(n in mocks)return mocks[n];throw Error('Dependência inesperada: '+n)},console})
 return m.exports
}
const validacao=importar('lib/wvetroValidacaoItem.ts')
const p=importar('lib/wvetroPreservacaoSincronizacao.ts',{'./wvetroValidacaoItem':validacao})
const item=(id,ambiente='Sala')=>({id,ambiente,tipo_esquadria:'porta_correr',tipo_outro_texto:null,folhas:'4',largura_mm:2800,altura_mm:2100,quantidade:1,cor:'preto',descricao:'porta',observacao_producao:null,contramarco:null})
const clone=x=>JSON.parse(JSON.stringify(x))
const antigo=[item('human-1'),item('human-2','Cozinha')]
const novo=[item('random-1'),item('random-2','Cozinha')]
const f=(n)=>({origem:'wvetro_api',numero:'384',payload_hash:'mesmo-hash',validacao_status:'aguardando',...n})
const conferir=(it,resultado='correto')=>({resultado,snapshot:validacao.snapshotItemWVetro(it),validado_em:'2026-10-16T20:00:00Z',validado_por_id:'usuario'})
const parcial=f({validacoes_itens:{'human-1':conferir(antigo[0])},validacao_por_item:true})
const res=p.reconciliarSincronizacaoWVetro({itens:clone(antigo),wvetro_fluxo:parcial},novo,f({sincronizado_em:'novo'}),true)
assert.equal(res.bloqueado,false)
assert.deepEqual(JSON.parse(JSON.stringify(res.itens)),antigo,'ID e dados humanos são preservados')
assert.equal(res.fluxo.validacao_status,'aguardando')
assert.equal(res.fluxo.validacao_por_item,true)
assert.equal(Object.keys(res.fluxo.validacoes_itens).length,1)
assert.equal(validacao.statusItemWVetro(res.itens[0],res.fluxo),'validado')
assert.equal(validacao.statusItemWVetro(res.itens[1],res.fluxo),'pendente')
const completo=f({validacoes_itens:{'human-1':conferir(antigo[0]),'human-2':conferir(antigo[1],'corrigido')},validacao_por_item:true,validacao_status:'validado',validado_em:'hoje',validado_por_nome:'Francis'})
const total=p.reconciliarSincronizacaoWVetro({itens:antigo,wvetro_fluxo:completo},novo,f({sincronizado_em:'novo'}),true)
assert.equal(total.fluxo.validacao_status,'validado')
assert.equal(total.fluxo.validado_em,'hoje')
assert.equal(total.fluxo.validado_por_nome,'Francis')
assert.equal(total.itens[1].id,'human-2')
assert.equal(p.houveConferenciaHumanaWVetro(completo),true)
assert.equal(p.houveConferenciaHumanaWVetro(parcial),true)
const diferente=p.reconciliarSincronizacaoWVetro({itens:antigo,wvetro_fluxo:parcial},novo,f({payload_hash:'outro'}),false)
assert.equal(diferente.bloqueado,true,'versão diferente não remove conferência humana')
assert.equal(diferente.itens[0].id,'human-1')
const livre=p.reconciliarSincronizacaoWVetro({itens:antigo,wvetro_fluxo:f({})},novo,f({payload_hash:'outro'}),false)
assert.equal(livre.bloqueado,false)
assert.equal(livre.itens[0].id,'random-1')
const semCheck=p.reconciliarSincronizacaoWVetro({itens:antigo,wvetro_fluxo:f({})},novo,f({}),true)
assert.equal(semCheck.itens[0].id,'human-1','reimportar payload igual não recria UUIDs mesmo sem validação')
const antigoLegado=p.reconciliarSincronizacaoWVetro({itens:antigo,wvetro_fluxo:f({validacao_status:'validado'})},novo,f({}),true)
assert.equal(antigoLegado.fluxo.validacao_status,'validado','não quebra validação legada')
const dezoito=Array.from({length:18},(_,i)=>item('real-'+i,'Ambiente '+i))
const validacoes18=Object.fromEntries(dezoito.map(i=>[i.id,conferir(i)]))
const dezoitoNovos=Array.from({length:18},(_,i)=>item('random-'+i,'Ambiente '+i))
const reimportado=p.reconciliarSincronizacaoWVetro({itens:dezoito,wvetro_fluxo:f({validacoes_itens:validacoes18,validacao_por_item:true,validacao_status:'validado'})},dezoitoNovos,f({}),true)
assert.equal(reimportado.fluxo.validacao_status,'validado')
assert.equal(Object.keys(reimportado.fluxo.validacoes_itens).length,18)
assert.deepEqual(JSON.parse(JSON.stringify(reimportado.itens.map(i=>i.id))),dezoito.map(i=>i.id))
const sync=fs.readFileSync('app/api/integracoes/wvetro/orcamentos/sincronizar/route.ts','utf8')
const kanban=fs.readFileSync('app/api/integracoes/wvetro/orcamentos/kanban/route.ts','utf8')
assert.match(sync,/reconciliarSincronizacaoWVetro\(existente, itens, fluxo, mesmoPayload\)/)
assert.match(sync,/alterado_durante_sincronizacao/)
assert.match(sync,/escrita\.select\('id'\)\.maybeSingle\(\)/)
assert.match(kanban,/houveConferenciaHumanaWVetro\(fluxoExistente\)/)
console.log('PASS: reimportação repetida, 18 tipologias, itens parciais, pacote alterado, UUIDs estáveis, confirmação legada, concorrência e vínculo manual')
