import assert from 'node:assert/strict'
import fs from 'node:fs'
const r=p=>fs.readFileSync(p,'utf8')
const api=r('app/api/kanban/configuracao-colunas/route.ts')
const acl=r('app/api/kanban/permissoes-colunas/route.ts')
const view=r('app/kanban/configuracao-colunas/page.tsx')
const painel=r('app/kanban/permissoes-colunas/page.tsx')
const sql=r('supabase/migrations/20261016063000_kanban_layout_permissoes_por_usuario_v1.sql')
assert.ok(acl.includes("u?.role==='master'"),'Only Master can grant privileges')
assert.ok(acl.includes('catalogoQuadros(u.empresa_id)'),'Board must be valid for company')
assert.ok(acl.includes("usuario.role==='master'"),'Existing Master not editable')
assert.ok(acl.includes(".eq('empresa_id',u.empresa_id)"),'Tenant filter in grant')
assert.ok(api.includes('permissao?.nivel!==\'gerenciar\''),'Only editor can POST')
assert.ok(api.includes("['consultar','gerenciar']"),'Only explicitly granted boards visible')
assert.ok(api.includes('cols.filter(c=>permitido(c.setor))'),'Result filtered by rights')
for(const x of ['const podeEditar=','disabled={!podeEditar','if(!podeEditar)return','somente para consulta'])assert.ok(view.includes(x),'UI must enforce read-only '+x)
assert.ok(painel.includes("'oculto'")&&painel.includes("'consultar'")&&painel.includes("'gerenciar'"),'Three explicit permission levels')
assert.ok(sql.includes('kanban_layout_permissoes_auditoria'),'Audit required')
assert.ok(sql.includes("and p.nivel='gerenciar'"),'Database refuses read-only users')
assert.ok(sql.includes('role=\'master\''),'Master retains access')
assert.ok(!sql.toLowerCase().includes('drop table'),'No destructive DDL')
console.log('PASS: board-level permissions, master-only grants, employee scopes, read-only UI, audited DB guard')
