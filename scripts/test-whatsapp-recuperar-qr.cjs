assert.match(api,/gateway_sem_sinal: !sinalRecente/)
assert.match(api,/status: !desconectar && !sinalRecente \? 202 : 200/)
assert.doesNotMatch(api,/session_slug: crypto\.randomUUID\(\)/,'Conectar não deve perder credenciais.')
assert.match(page,/role="status" aria-live="polite"/)
assert.match(page,/Gateway sem comunicação recente/)
assert.match(page,/executando\[canal.id\]/)
assert.match(page,/Solicitando\.\.\./)
assert.match(page,/Conectar \/ recuperar QR/)
assert.match(edge,/gateway_reconnect_requested_at,nivel_hierarquia/)
assert.match(gateway,/reconnectRequestsHandled/)
assert.match(gateway,/channel\.gateway_reconnect_requested_at/)
assert.match(gateway,/await disconnectChannel\(channel.id, false\)/)
assert.match(gateway,/sessions\.get\(channel.id\) === stateEntry/)
assert.match(gateway,/syncFullHistory: true/)
assert.match(gateway,/fs\.renameSync\(sessionDir/)
