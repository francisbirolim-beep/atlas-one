const assert=require('node:assert/strict')
const fs=require('node:fs')
const api=fs.readFileSync('app/api/integracoes/whatsapp/canais/route.ts','utf8')
const page=fs.readFileSync('app/whatsapp/numeros/page.tsx','utf8')
const gateway=fs.readFileSync('scripts/whatsapp-gateway.mjs','utf8')
const edge=fs.readFileSync('supabase/functions/whatsapp-gateway/index.ts','utf8')
