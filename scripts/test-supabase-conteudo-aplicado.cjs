const fs=require('node:fs')
const path=require('node:path')
const crypto=require('node:crypto')
const assert=require('node:assert/strict')
const md5=v=>crypto.createHash('md5').update(v).digest('hex')
const sha256=v=>crypto.createHash('sha256').update(v).digest('hex')
const manifest=JSON.parse(fs.readFileSync('docs/supabase-applied-content-reconciliation-manifest.json','utf8'))
const prior=JSON.parse(fs.readFileSync('docs/supabase-migration-reconciliation-manifest.json','utf8'))
const active=fs.readdirSync('supabase/migrations').filter(f=>f.endsWith('.sql'))
const versions=active.map(f=>f.slice(0,14))
assert.equal(versions.length,new Set(versions).size,'Versão duplicada de migração')
assert.ok(active.length>=manifest.active_versions_after,'Uma versão histórica desapareceu')
assert.equal(manifest.entries.length,87,'Manifesto precisa cobrir as 87 divergências')
assert.equal(new Set(manifest.entries.map(x=>x.version)).size,87,'Versão auditada duplicada')
const oldByVersion=new Map(prior.same_version_differences.map(x=>[x.version,x]))
for(const entry of manifest.entries){
 const previous=oldByVersion.get(entry.version)
 assert.ok(previous,'Versão não consta da auditoria anterior: '+entry.version)
 assert.equal(entry.active_file,'supabase/migrations/'+previous.local_file)
 assert.equal(entry.original_file,'supabase/migrations-review/20261010-content-differences/'+previous.local_file)
 const applied=fs.readFileSync(entry.active_file)
 const original=fs.readFileSync(entry.original_file)
 assert.equal(md5(applied),entry.applied_md5,'SQL aplicado foi modificado: '+entry.version)
 assert.equal(md5(applied),previous.remote_md5,'SQL aplicado não corresponde ao banco: '+entry.version)
 assert.equal(md5(original),previous.local_md5,'Original histórico foi modificado: '+entry.version)
 assert.equal(sha256(original),entry.original_sha256,'Original de backup corrompido: '+entry.version)
 assert.equal(original.length,entry.original_length)
 assert.equal(applied.length,entry.applied_length)
 assert.notEqual(md5(original),md5(applied),'Não era diferença real: '+entry.version)
}
const preserved=fs.readdirSync('supabase/migrations-review/20261010-content-differences').filter(f=>f.endsWith('.sql'))
assert.equal(preserved.length,87,'Backups originais faltantes ou extras')
for(const file of preserved){
 assert.ok(manifest.entries.some(x=>x.original_file.endsWith('/'+file)),'Backup não inventariado: '+file)
}
console.log('PASS: 87 SQLs aplicados conferidos por MD5, 87 originais intactos, sem versões duplicadas.')
