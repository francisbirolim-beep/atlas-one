const assert=require('node:assert/strict')
const fs=require('node:fs')
const vm=require('node:vm')
const ts=require('typescript')
const file='lib/ai/equivalenciaPerfilTecnico.ts'
const m={exports:{}}
vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{
  compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}
}).outputText,{module:m,exports:m.exports})
const {compararGeometria,codigoPerfil,classificarFuncaoDeclarada}=m.exports
assert.equal(codigoPerfil('SU-289'),'SU289')
assert.equal(codigoPerfil('XY_010'),'XY010')
const a={codigo:'SU-289',categoria:'perfil',peso_kg_m:0.272,medidas_mm:{A:50.8,B:1}}
const b={codigo:'T-77',categoria:'perfil',peso_kg_m:0.251,medidas_mm:{A:50.8,B:1.0}}
const eq=compararGeometria(a,b)
assert.equal(eq.medidasCompativeis,true,'Códigos diferentes são permitidos com geometrias compatíveis')
assert.equal(eq.medidasComuns,2)
assert.equal(compararGeometria(a,{...b,medidas_mm:{A:47,B:1}}).medidasCompativeis,false,'Diferença grande impede vínculo')
assert.equal(compararGeometria(a,{...b,medidas_mm:{A:50.8}}).medidasCompativeis,false,'Exigir duas cotas')
assert.equal(compararGeometria(a,{...b,categoria:'acessorio'}).medidasCompativeis,false,'Categorias incompatíveis')
assert.equal(compararGeometria(a,{...b,medidas_mm:{A:50.8,B:1.25}}).divergentes.length,1)
assert.equal(classificarFuncaoDeclarada('Travessa inferior',null),'Travessa')
assert.equal(classificarFuncaoDeclarada('Perfil XY',null),'Função ainda não identificada')
const route=fs.readFileSync('app/api/ia/central-aprendizado/route.ts','utf8')
const ui=fs.readFileSync('app/atlas-ia/aprendizado/CompararPerfilCatalogo.tsx','utf8')
assert.match(route,/const candidatoComparar=txt\(req\.nextUrl\.searchParams\.get\('compararPerfil'\)/)
assert.match(route,/if\(acao==='vincular_equivalente_perfil'\)/)
assert.match(route,/confirmar_equivalencia!==true/)
assert.match(route,/compararGeometria\(/)
assert.match(route,/if\(!medidas\.medidasCompativeis\)/)
assert.match(route,/imagem_confirmada!==true/)
assert.match(route,/imagem_codigo_validado/)
assert.match(route,/produto_fornecedores/)
assert.match(route,/fornecedor_catalogo_itens/)
assert.match(route,/equivalencia_confirmada_com/)
assert.match(route,/peso_kg_m:pesoDecimalCatalogo\(d\.peso_kg_m\)/)
assert.match(route,/\.eq\('updated_at',c\.updated_at\)/)
assert.match(route,/if\(process\.env\.VERCEL_ENV==='preview'\)/)
assert.match(ui,/Comparar lado a lado/)
assert.match(ui,/Nenhum dado real foi alterado/)
assert.match(ui,/peso: \{f\.peso_kg_m/)
assert.match(ui,/fotoNota==null\?'comparação visual indisponível'/)
assert.match(ui,/Simular vínculo entre fornecedores/)
const old=fs.readFileSync('app/atlas-ia/aprendizado/page.tsx','utf8')
assert.match(old,/Arquivar material/)
assert.match(old,/CompararPerfilCatalogo/)
console.log('PASS: códigos diferentes com cotas iguais; conflito e imagens protegidos; fornecedor e peso próprios; sem mesclagem automática; arquivamento mantido.')
