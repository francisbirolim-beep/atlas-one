const assert=require('node:assert/strict')
const fs=require('node:fs')
const ui=fs.readFileSync('app/whatsapp/page.tsx','utf8')
const api=fs.readFileSync('app/api/integracoes/whatsapp/midia/route.ts','utf8')
const backend=fs.readFileSync('lib/whatsappServer.ts','utf8')
const messaging=fs.readFileSync('app/api/integracoes/whatsapp/mensagens/route.ts','utf8')
const gateway=fs.readFileSync('scripts/whatsapp-gateway.mjs','utf8')
for(const msg of ['Baixar imagem','Baixar PDF','Baixar documento','Baixar áudio','Baixar vídeo']){
 if(msg==='Baixar PDF')assert.match(ui,/\?'PDF':'documento'/)
 else if(msg==='Baixar documento')assert.match(ui,/Baixar \{String\(m\.mime_type/)
 else assert.ok(ui.includes(msg),msg)
}
assert.match(ui,/setMensagemRespondendo\(m\)/,'Responder continua selecionando a mensagem')
assert.match(ui,/setEmojiMensagemId\(atual=>atual===m\.id\?null:m\.id\)/,'Emojis continuam selecionando a mensagem')
assert.match(ui,/mb-2 flex flex-wrap items-center gap-1 border-b/,'Ações visíveis em todas as resoluções sem hover')
assert.match(ui,/!m\.whatsapp_message_id/,'Não oferece resposta a mensagens antigas sem ID remoto')
assert.match(ui,/respostaMensagemId: mensagemRespondendo\?\.id \|\| null/)
assert.match(messaging,/reagirMensagemWhatsApp/,'Reagir passa pela autorização de atendimento')
assert.match(ui,/\['audio\/webm;codecs=opus','audio\/mp4','audio\/ogg;codecs=opus'\]/)
assert.match(ui,/gravador\.mimeType \|\| partesAudioRef\.current\[0\]\?\.type/,'Tipo real do áudio, inclusive Safari')
assert.doesNotMatch(ui,/new Blob\(partesAudioRef\.current, \{ type: 'audio\/webm' \}\)/)
assert.match(gateway,/quotedWhatsappMessageId/,'Mantém reply enviado como citação no WhatsApp')
assert.match(gateway,/reactionTargetWhatsappId/,'Mantém reação no WhatsApp')
assert.match(api,/assinarDownloadMidiaAtendimento/,'Download passa por servidor autenticado')
assert.match(backend,/conversaAcessivel\(conversaId, usuario, true\)/)
assert.match(backend,/\.eq\('empresa_id', usuario\.empresa_id\)/)
assert.match(backend,/\.in\('conversa_id', ids\.length \? ids : \[conversaId\]\)/)
assert.match(backend,/\.createSignedUrl\(caminho, 10 \* 60, \{ download: nome \}\)/)
assert.doesNotMatch(backend,/downloadUrl = .*req\./,'Nunca confiar em URL enviada pelo cliente')
console.log('PASS: reply, emoji, áudio multi-navegador e download autorizado sem alterar fluxos existentes.')
