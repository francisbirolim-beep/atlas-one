assert.equal(descricaoMedidaPadrao({produtoNome:'',tipoOutroTexto:'',descricao:''}),'')
const tela = fs.readFileSync(path.join(root,'app/orcamento-rapido/page.tsx'),'utf8')
const envio = fs.readFileSync(path.join(root,'lib/orcamentos.ts'),'utf8')
assert.match(tela,/onChange\(\{tipo:'outro',tipoOutroTexto:texto,produtoNome:texto,produtoId:null,precoUnit:null,modoOrigem:'manual'\}\)/,'Digitado precisa entrar no ItemForm, inclusive no rascunho automático')
assert.match(tela,/useState\(item.produtoNome \|\| item.tipoOutroTexto \|\| ''\)/,'Ao restaurar o rascunho a busca precisa ter o valor salvo')
assert.match(tela,/if \(it.itemTipo === 'medida_padrao'\)/,'Medida padrão manual tem validação independente de catálogo')
assert.match(tela,/!descricaoMedidaPadrao\(it\)/,'Sem produto cadastrado, exigir apenas descrição não vazia')
assert.match(envio,/const nomeProdutoItem = itemTipo === 'kit_porta_pronta'[\s\S]{0,340}descricaoMedidaPadrao\(it\)/,'Descrição manual é registrada em produto_nome')
assert.match(envio,/const produto_id = it.modoOrigem === 'produto' \? \(it.produtoId \|\| null\) : null/,'Item livre não ganha produto_id inventado')
assert.match(envio,/const preco_unit = it.modoOrigem === 'produto' && it.precoUnit != null \? it.precoUnit : null/,'Item livre não recebe preço fictício')
assert.equal((envio.match(/descricao: descricaoItem/g)||[]).length,2,'Registra descrição nos dois tipos de medida')
