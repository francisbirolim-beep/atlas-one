const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const vm = require('node:vm')
const root = path.resolve(__dirname, '..')
const content = fs.readFileSync(path.join(root, 'lib/orcamentoRapidoProdutoLivre.ts'), 'utf8')
const js = ts.transpileModule(content, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText
const moduleRef = {exports:{}}
vm.runInNewContext(js,{module:moduleRef,exports:moduleRef.exports})
const {descricaoMedidaPadrao} = moduleRef.exports
assert.equal(descricaoMedidaPadrao({produtoNome:'  PORTA DE GIRO 95  '}),'PORTA DE GIRO 95')
assert.equal(descricaoMedidaPadrao({tipoOutroTexto:' VENEZIANA LAMBRI 1500 X 1000 '}),'VENEZIANA LAMBRI 1500 X 1000')
