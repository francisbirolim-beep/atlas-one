-- Atlas One — PDV Balcão v1
-- Dependência: estoque/precificação da PR #255.

create table if not exists public.balcao_caixas (
  id uuid primary key default gen_random_uuid(),
  status text not null default 'aberto' check (status in ('aberto','fechado')),
  operador_id uuid not null references auth.users(id),
  operador_nome text not null,
  aberto_em timestamptz not null default now(),
  saldo_inicial numeric not null default 0 check (saldo_inicial >= 0),
  fechado_em timestamptz,
  fechado_por_id uuid references auth.users(id),
  fechado_por_nome text,
  saldo_esperado numeric,
  saldo_contado numeric,
  diferenca numeric,
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists uq_balcao_caixa_operador_aberto
  on public.balcao_caixas(operador_id) where status='aberto';

create table if not exists public.balcao_vendas (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  status text not null default 'finalizada' check (status in ('finalizada','cancelada','devolvida_parcial')),
  cliente_id uuid references public.clientes(id) on delete set null,
  cliente_nome text,
  vendedor_id uuid not null references auth.users(id),
  vendedor_nome text not null,
  caixa_id uuid not null references public.balcao_caixas(id),
  subtotal numeric not null check (subtotal >= 0),
  desconto numeric not null default 0 check (desconto >= 0),
  total numeric not null check (total >= 0),
  observacoes text,
  finalizada_em timestamptz not null default now(),
  cancelada_em timestamptz,
  cancelada_por_id uuid references auth.users(id),
  cancelada_por_nome text,
  motivo_cancelamento text,
  created_at timestamptz not null default now()
);
create index if not exists idx_balcao_vendas_data on public.balcao_vendas(finalizada_em desc);
create index if not exists idx_balcao_vendas_cliente on public.balcao_vendas(cliente_id, finalizada_em desc);

create table if not exists public.balcao_venda_itens (
  id uuid primary key default gen_random_uuid(),
  venda_id uuid not null references public.balcao_vendas(id) on delete restrict,
  produto_id uuid not null references public.produtos(id),
  produto_codigo text,
  produto_nome text not null,
  unidade text,
  quantidade numeric not null check (quantidade > 0),
  custo_unitario_snapshot numeric,
  preco_tabela_snapshot numeric,
  preco_unitario numeric not null check (preco_unitario >= 0),
  preco_minimo_snapshot numeric,
  total_item numeric not null check (total_item >= 0),
  margem_real_percentual numeric,
  created_at timestamptz not null default now()
);
create index if not exists idx_balcao_venda_itens_venda on public.balcao_venda_itens(venda_id);
create index if not exists idx_balcao_venda_itens_produto on public.balcao_venda_itens(produto_id, created_at desc);

create table if not exists public.balcao_pagamentos (
  id uuid primary key default gen_random_uuid(),
  venda_id uuid not null references public.balcao_vendas(id) on delete restrict,
  forma text not null check (forma in ('dinheiro','pix','cartao_debito','cartao_credito','boleto','a_prazo','outros')),
  valor numeric not null check (valor > 0),
  parcelas integer not null default 1 check (parcelas > 0),
  detalhes text,
  created_at timestamptz not null default now()
);
create index if not exists idx_balcao_pagamentos_venda on public.balcao_pagamentos(venda_id);

create table if not exists public.balcao_caixa_movimentos (
  id uuid primary key default gen_random_uuid(),
  caixa_id uuid not null references public.balcao_caixas(id),
  venda_id uuid references public.balcao_vendas(id) on delete set null,
  tipo text not null check (tipo in ('abertura','recebimento','suprimento','sangria','estorno','ajuste','fechamento')),
  forma_pagamento text,
  entrada numeric not null default 0 check (entrada >= 0),
  saida numeric not null default 0 check (saida >= 0),
  descricao text,
  criado_por_id uuid not null references auth.users(id),
  criado_por_nome text not null,
  created_at timestamptz not null default now(),
  constraint balcao_caixa_movimento_valor check (entrada > 0 or saida > 0 or tipo in ('abertura','fechamento'))
);
create index if not exists idx_balcao_caixa_movimentos_caixa on public.balcao_caixa_movimentos(caixa_id, created_at desc);

create table if not exists public.financeiro_contas_receber (
  id uuid primary key default gen_random_uuid(),
  venda_balcao_id uuid references public.balcao_vendas(id) on delete set null,
  cliente_id uuid references public.clientes(id) on delete set null,
  cliente_nome text,
  documento text,
  parcela integer not null default 1,
  total_parcelas integer not null default 1,
  data_emissao date not null default current_date,
  vencimento date,
  valor numeric not null check (valor >= 0),
  status text not null default 'aberto' check (status in ('aberto','pago','cancelado','vencido')),
  forma text,
  data_pagamento date,
  valor_pago numeric,
  observacoes text,
  criado_por_id uuid references auth.users(id),
  criado_por_nome text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_contas_receber_status_venc on public.financeiro_contas_receber(status, vencimento);

