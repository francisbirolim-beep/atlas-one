  ('caixa-balcao','Caixa Balcão','Administrativo',35,true,'/balcao/caixa','Abertura, suprimento, sangria e fechamento do caixa.'),
  ('relatorios-balcao','Relatórios Balcão','Administrativo',36,true,'/balcao/relatorios','Indicadores, margens e relatórios gerenciais do PDV.')
on conflict (id) do update set nome=excluded.nome, grupo=excluded.grupo, ativo=true, rota=excluded.rota, descricao=excluded.descricao;

