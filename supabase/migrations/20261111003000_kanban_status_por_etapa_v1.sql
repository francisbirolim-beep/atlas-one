-- Status visuais por venda/coluna, independentes das operações oficiais.
-- Apenas o backend autenticado utiliza esta API. Nenhuma permissão de escrita pública.
create table if not exists public.visao_geral_cards_status_etapa (
  empresa_id uuid not null,
  venda_id uuid not null references public.vendas_obras(id) on delete cascade,
  coluna_id text not null,
  status_ids text[] not null default '{}'::text[],
  atualizado_por_id uuid,
  updated_at timestamptz not null default now(),
  primary key (empresa_id, venda_id, coluna_id),
  constraint visao_geral_status_etapa_max_status check (cardinality(status_ids) <= 24),
  constraint visao_geral_status_etapa_coluna check (length(coluna_id) between 1 and 100)
);
create index if not exists idx_visao_geral_cards_status_venda
on public.visao_geral_cards_status_etapa(empresa_id, venda_id);

create table if not exists public.visao_geral_cards_status_etapa_historico (
  id bigint generated by default as identity primary key,
  empresa_id uuid not null,
  venda_id uuid not null,
  coluna_id text not null,
  status_anteriores text[] not null default '{}'::text[],
  status_novos text[] not null default '{}'::text[],
  usuario_id uuid not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_visao_geral_status_historico_venda
on public.visao_geral_cards_status_etapa_historico(empresa_id, venda_id, created_at desc);

alter table public.visao_geral_cards_status_etapa enable row level security;
alter table public.visao_geral_cards_status_etapa_historico enable row level security;
revoke all on table public.visao_geral_cards_status_etapa from public, anon, authenticated;
revoke all on table public.visao_geral_cards_status_etapa_historico from public, anon, authenticated;

-- Transação atômica e auditável. Autorização funcional é exigida previamente pela API.
-- SECURITY INVOKER e EXECUTE exclusivo do service_role: não conceder ao cliente web.
create or replace function public.salvar_visao_geral_status_etapa_v1(
  p_empresa uuid, p_usuario uuid, p_venda uuid, p_coluna_id text, p_status_ids text[]
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $func$
declare
  v_colunas jsonb;
  v_coluna jsonb;
  v_antigos text[] := '{}'::text[];
  v_novos text[] := coalesce(p_status_ids, '{}'::text[]);
  v_distintos integer;
  v_valido boolean;
begin
  if not exists (select 1 from public.usuarios
    where id = p_usuario and empresa_id = p_empresa) then
    raise exception 'Usuário não pertence à empresa';
  end if;
  if not exists (select 1 from public.vendas_obras
    where id = p_venda and empresa_id = p_empresa and excluida_em is null) then
    raise exception 'Venda inválida para a empresa';
  end if;
  if p_coluna_id is null or p_coluna_id !~ '^[a-zA-Z0-9_-]{1,100}$' then
    raise exception 'Identificador da coluna inválido';
  end if;
  if cardinality(v_novos) > 24 then
    raise exception 'Quantidade máxima de status excedida';
  end if;
  select count(distinct id) into v_distintos from unnest(v_novos) as id;
  if v_distintos <> cardinality(v_novos) then
    raise exception 'Status duplicado';
  end if;
  select colunas into v_colunas from public.visao_geral_configuracoes where empresa_id = p_empresa;
  if v_colunas is null then raise exception 'Configure as colunas antes de usar os status'; end if;
  select entrada.value into v_coluna
    from jsonb_array_elements(v_colunas) as entrada(value)
    where entrada.value->>'id' = p_coluna_id limit 1;
  if v_coluna is null then raise exception 'Coluna não pertence ao Kanban'; end if;
  select not exists(
    select 1 from unnest(v_novos) as selecionado(id)
    where not exists(
      select 1 from jsonb_array_elements(coalesce(v_coluna->'statusDisponiveis', '[]'::jsonb)) as disponivel(value)
      where disponivel.value->>'id' = selecionado.id
    )
  ) into v_valido;
  if not v_valido then raise exception 'Status desconhecido ou desativado'; end if;

  select status_ids into v_antigos
  from public.visao_geral_cards_status_etapa
  where empresa_id = p_empresa and venda_id = p_venda and coluna_id = p_coluna_id
  for update;
  v_antigos := coalesce(v_antigos, '{}'::text[]);
  if v_antigos = v_novos then
    return jsonb_build_object('ok', true, 'statusIds', v_novos);
  end if;
  insert into public.visao_geral_cards_status_etapa
    (empresa_id, venda_id, coluna_id, status_ids, atualizado_por_id)
    values(p_empresa, p_venda, p_coluna_id, v_novos, p_usuario)
  on conflict (empresa_id, venda_id, coluna_id)
  do update set status_ids = excluded.status_ids,
    atualizado_por_id = excluded.atualizado_por_id, updated_at = now();

  insert into public.visao_geral_cards_status_etapa_historico
    (empresa_id, venda_id, coluna_id, status_anteriores, status_novos, usuario_id)
    values (p_empresa, p_venda, p_coluna_id, v_antigos, v_novos, p_usuario);

  return jsonb_build_object('ok', true, 'statusIds', v_novos);
end;
$func$;
revoke all on function public.salvar_visao_geral_status_etapa_v1(uuid,uuid,uuid,text,text[]) from public, anon, authenticated;
grant execute on function public.salvar_visao_geral_status_etapa_v1(uuid,uuid,uuid,text,text[]) to service_role;
