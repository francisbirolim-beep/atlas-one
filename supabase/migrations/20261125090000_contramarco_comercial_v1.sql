-- Comercial independente: não alimenta vendas_obras, financeiro ou produção de esquadrias.
create table if not exists public.orcamentos_contramarco (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  empresa_id uuid not null references public.empresas(id),
  cliente_id uuid not null references public.clientes(id) on delete restrict,
  origem_orcamento_id uuid references public.orcamentos(id) on delete restrict,
  origem_medicao_id uuid references public.medicoes_finais(id) on delete restrict,
  nome_obra text not null check (length(trim(nome_obra)) between 1 and 150),
  endereco text not null default '',
  cidade text not null default '',
  condicoes text not null default '',
  itens jsonb not null check (jsonb_typeof(itens)='array' and jsonb_array_length(itens) between 1 and 100),
  valor_centavos bigint not null check (valor_centavos >= 0),
  status text not null default 'rascunho' check (status in ('rascunho','proposta','vendido','cancelado')),
  versao integer not null default 1 check (versao>0),
  criado_por uuid not null references public.usuarios(id),
  atualizado_por uuid not null references public.usuarios(id),
  confirmado_por uuid references public.usuarios(id),
  confirmado_em timestamptz,
  cancelado_por uuid references public.usuarios(id),
  cancelado_em timestamptz,
  motivo_cancelamento text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status <> 'vendido' or (confirmado_por is not null and confirmado_em is not null and valor_centavos>0)),
  check (status <> 'cancelado' or (cancelado_por is not null and cancelado_em is not null and length(trim(motivo_cancelamento))>=3))
);
create index if not exists orcamentos_contramarco_cliente_idx on public.orcamentos_contramarco(empresa_id,cliente_id,created_at desc);
create unique index if not exists orcamentos_contramarco_medicao_ativa_idx on public.orcamentos_contramarco(empresa_id,origem_medicao_id) where origem_medicao_id is not null and status <> 'cancelado';
create unique index if not exists orcamentos_contramarco_origem_ativa_idx on public.orcamentos_contramarco(empresa_id,origem_orcamento_id) where origem_orcamento_id is not null and status <> 'cancelado';
alter table public.orcamentos_contramarco enable row level security;
revoke all on public.orcamentos_contramarco from anon, authenticated;
grant select, insert, update on public.orcamentos_contramarco to service_role;
grant usage, select on sequence public.orcamentos_contramarco_numero_seq to service_role;

create or replace function public.guard_orcamento_contramarco_v1() returns trigger
language plpgsql set search_path='' as $$
begin
  if not exists(select 1 from public.clientes c where c.id=new.cliente_id and c.empresa_id=new.empresa_id) then
    raise exception 'Cliente incompatível com a empresa';
  end if;
  if new.origem_orcamento_id is not null and not exists(select 1 from public.orcamentos o where o.id=new.origem_orcamento_id and o.empresa_id=new.empresa_id and o.cliente_id=new.cliente_id) then
    raise exception 'Orçamento de origem incompatível';
  end if;
  if new.origem_medicao_id is not null and not exists(select 1 from public.medicoes_finais m where m.id=new.origem_medicao_id and m.empresa_id=new.empresa_id and m.cliente_id=new.cliente_id and m.tipo_medicao='contramarco' and (new.origem_orcamento_id is null or m.orcamento_id=new.origem_orcamento_id)) then
    raise exception 'Medição de origem incompatível';
  end if;
  if not exists(select 1 from public.usuarios u where u.id=new.criado_por and u.empresa_id=new.empresa_id)
    or not exists(select 1 from public.usuarios u where u.id=new.atualizado_por and u.empresa_id=new.empresa_id)
    or (new.confirmado_por is not null and not exists(select 1 from public.usuarios u where u.id=new.confirmado_por and u.empresa_id=new.empresa_id))
    or (new.cancelado_por is not null and not exists(select 1 from public.usuarios u where u.id=new.cancelado_por and u.empresa_id=new.empresa_id)) then
    raise exception 'Autor incompatível com a empresa';
  end if;
  if tg_op='INSERT' then
    if new.status<>'rascunho' or new.versao<>1 then raise exception 'Crie primeiro o rascunho'; end if;
  else
    if new.empresa_id<>old.empresa_id or new.cliente_id<>old.cliente_id or new.numero<>old.numero or new.criado_por<>old.criado_por
      or new.origem_orcamento_id is distinct from old.origem_orcamento_id
      or (new.origem_medicao_id is distinct from old.origem_medicao_id and not (old.status='rascunho' and new.status='rascunho' and old.origem_medicao_id is null and new.origem_medicao_id is not null and old.origem_orcamento_id is not null))
      or new.versao<>old.versao+1 then raise exception 'Vínculo ou versão inválida'; end if;
    if old.status='cancelado' or (old.status='rascunho' and new.status not in ('rascunho','proposta','cancelado'))
      or (old.status='proposta' and new.status not in ('vendido','cancelado'))
      or (old.status='vendido' and new.status<>'cancelado') then raise exception 'Transição comercial inválida'; end if;
    if old.status in ('proposta','vendido') and (new.itens is distinct from old.itens or new.valor_centavos<>old.valor_centavos
      or new.nome_obra<>old.nome_obra or new.endereco<>old.endereco or new.cidade<>old.cidade or new.condicoes<>old.condicoes) then
      raise exception 'Proposta emitida ou venda não pode ser reescrita';
    end if;
  end if;
  return new;
end $$;
revoke all on function public.guard_orcamento_contramarco_v1() from public, anon, authenticated;
create trigger guard_orcamento_contramarco before insert or update on public.orcamentos_contramarco
for each row execute function public.guard_orcamento_contramarco_v1();
